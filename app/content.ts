export const essayPosts = staticPosts.filter((p) => p.kind === "essay");
export const diaryPosts = staticPosts.filter((p) => p.kind === "diary");

export const featuredPost = staticPosts.find((p) => p.featured) || staticPosts[0];

export function getPost(slug: string) {
  return staticPosts.find((p) => p.slug === slug);
}

export function getAdjacentPosts(slug: string) {
  const index = staticPosts.findIndex((p) => p.slug === slug);
  return {
    previous: index > 0 ? staticPosts[index - 1] : null,
    next: index < staticPosts.length - 1 ? staticPosts[index + 1] : null,
  };
}
